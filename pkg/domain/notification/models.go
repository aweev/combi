package notification

import (
	"time"

	"github.com/combi/pkg/domain/core"
	"github.com/combi/pkg/security"
	"github.com/google/uuid"
)

// --- Enums ---

type NotificationChannel string

const (
	ChannelEmail   NotificationChannel = "EMAIL"
	ChannelSMS     NotificationChannel = "SMS"
	ChannelPush    NotificationChannel = "PUSH"
	ChannelInApp   NotificationChannel = "IN_APP"
	ChannelWebhook NotificationChannel = "WEBHOOK"
	ChannelWebPush NotificationChannel = "WEB_PUSH"
)

type NotificationStatus string

const (
	StatusPending   NotificationStatus = "PENDING"   // Created, waiting to be queued.
	StatusQueued    NotificationStatus = "QUEUED"    // Job dispatched for processing.
	StatusSending   NotificationStatus = "SENDING"   // Dequeued, actively being sent to provider.
	StatusSent      NotificationStatus = "SENT"      // Provider accepted the message.
	StatusDelivered NotificationStatus = "DELIVERED" // Provider confirmed delivery.
	StatusFailed    NotificationStatus = "FAILED"    // A failure occurred.
	StatusBounced   NotificationStatus = "BOUNCED"   // Email hard bounce.
	StatusCancelled NotificationStatus = "CANCELLED" // Cancelled before sending.
	StatusRead      NotificationStatus = "READ"      // Recipient opened/read the message.
)

type TemplateType string

const (
	TemplateTypeTransactional TemplateType = "TRANSACTIONAL"
	TemplateTypeMarketing     TemplateType = "MARKETING"
	TemplateTypeSystem        TemplateType = "SYSTEM"
)

type PreferenceScope string

const (
	ScopeGlobal       PreferenceScope = "GLOBAL"       // e.g., Mute all SMS.
	ScopeCategory     PreferenceScope = "CATEGORY"     // e.g., Mute "marketing" emails.
	ScopeNotification PreferenceScope = "NOTIFICATION" // e.g., Unsubscribe from a newsletter template.
)

type ProviderType string

const (
	ProviderSMTP   ProviderType = "SMTP"
	ProviderTwilio ProviderType = "TWILIO"
	ProviderBrevo  ProviderType = "BREVO"
	ProviderFCM    ProviderType = "FCM"
	ProviderLog    ProviderType = "LOG" // Dummy provider for testing.
)

type EventSource string

const (
	SourceInternal EventSource = "INTERNAL" // Event generated by our system (e.g., "queued").
	SourceProvider EventSource = "PROVIDER" // Event from a provider webhook (e.g., "delivered").
)

// --- Core Models ---

// Notification represents a single message instance sent to a recipient.
type Notification struct {
	ID           uuid.UUID
	RecipientID  uuid.UUID
	Channel      NotificationChannel
	Status       NotificationStatus
	TemplateID   *uuid.UUID       // If sent from a template
	Subject      *string          // Rendered subject
	Body         string           // Rendered body
	Data         map[string]any   // Variables used for rendering
	ToAddress    core.Email       // Email, phone number, etc.
	Category     string           // e.g., "authentication", "billing"
	Reference    *NotificationRef // Link to the originating entity
	SentAt       *time.Time
	DeliveredAt  *time.Time
	ReadAt       *time.Time
	Attempts     int
	LastError    *string
	ProviderName string  // e.g. "sendgrid-primary"
	ProviderID   *string // External ID
	CreatedAt    time.Time
	UpdatedAt    time.Time
}

// NotificationRef links a notification to the business entity that triggered it.
type NotificationRef struct {
	EntityType string
	EntityID   uuid.UUID
}

// NotificationTemplate is a reusable template.
type NotificationTemplate struct {
	ID          uuid.UUID
	Name        string
	Slug        string // Unique identifier e.g. "welcome-email"
	Description string
	Type        TemplateType
	Category    string
	Channel     NotificationChannel
	IsActive    bool
	Locale      string  // Primary locale
	Subject     *string // Template string
	Body        string  // Template string
	Version     int
	CreatedBy   uuid.UUID
	CreatedAt   time.Time
	UpdatedAt   time.Time
}

// TemplateTranslation represents a localized version.
type TemplateTranslation struct {
	ID         uuid.UUID
	TemplateID uuid.UUID
	Locale     string
	Subject    *string
	Body       string
	CreatedAt  time.Time
	UpdatedAt  time.Time
}

// NotificationPreference stores a user's choice.
type NotificationPreference struct {
	ID         uuid.UUID
	UserID     uuid.UUID
	Channel    NotificationChannel
	Scope      PreferenceScope
	Category   *string    // For ScopeCategory
	TemplateID *uuid.UUID // For ScopeNotification
	IsEnabled  bool
	CreatedAt  time.Time
	UpdatedAt  time.Time
}

// NotificationProvider is the model for a configured third-party service.
type NotificationProvider struct {
	ID        uuid.UUID
	Name      string
	Type      ProviderType
	Channel   NotificationChannel
	IsActive  bool
	Config    EncryptedConfig // Stores API Keys
	CreatedAt time.Time
	UpdatedAt time.Time
}

type EncryptedConfig struct {
	EncryptedData     []byte
	EncryptionContext *security.EncryptionContext
}

// NotificationEvent is an immutable lifecycle log.
type NotificationEvent struct {
	ID             uuid.UUID
	NotificationID uuid.UUID
	Source         EventSource
	EventType      string
	Message        string
	Details        map[string]any
	CreatedAt      time.Time
}

// NotificationStats represents aggregated statistics.
type NotificationStats struct {
	TotalSent      int64
	TotalDelivered int64
	TotalFailed    int64
	TotalRead      int64
	ByStatus       map[NotificationStatus]int64
}

type NotificationSentPayload struct {
	NotificationID uuid.UUID `json:"notification_id"`
	RecipientID    uuid.UUID `json:"recipient_id"`
	Channel        string    `json:"channel"` // "email", "sms", "in-app"
	Category       string    `json:"category"`
	SentAt         time.Time `json:"sent_at"`
	// For in-app notifications, we might include content preview
	Subject string `json:"subject,omitempty"`
}
