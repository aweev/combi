// renderGo executes a Go source template and gofmts the result, so the
// generator can never emit unformatted or invalid Go.
func renderGo(t *template.Template, data any) ([]byte, error) {
	var buf bytes.Buffer
	if err := t.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("execute %s: %w", t.Name(), err)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt %s: %w\n--- source ---\n%s", t.Name(), err, buf.String())
	}
	return src, nil
}

// renderText executes a template without gofmt (go.mod, README.md).
func renderText(t *template.Template, data any) ([]byte, error) {
	var buf bytes.Buffer
	if err := t.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("execute %s: %w", t.Name(), err)
	}
	return buf.Bytes(), nil
}
