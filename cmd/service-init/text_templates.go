// renderTextBackticked renders a template and swaps %%BT%% for backticks.
func renderTextBackticked(t *template.Template, data any) ([]byte, error) {
	raw, err := renderText(t, data)
	if err != nil {
		return nil, err
	}
	return []byte(strings.ReplaceAll(string(raw), "%%BT%%", "`")), nil
}
